const files = getAllHtmlFiles('.');
let enrichedCount = 0;

for (const file of files) {
  let slug = path.dirname(file).replace(/\\/g, '/').replace(/^\.\//, '');
  if (slug === '.') slug = 'home';
  if (['about-us', 'contact-us', 'privacy-policy', 'terms-conditions-aio-calculator', 'disclaimer-aio-calculator', 'free-online-dice-roller'].includes(slug)) continue;

  let html = fs.readFileSync(file, 'utf8');
  let currentWords = countWords(html);

  if (currentWords < 1200) {
    let enrichment = '';
    if (['financial-calculators', 'fitness-health-calculators', 'math-calculators', 'everyday-tools', 'all-tools', 'blog', 'home'].includes(slug)) {
      enrichment = getCategoryContent(slug);
    } else if (file.includes('finance') || slug.includes('mortgage') || slug.includes('loan') || slug.includes('interest') || slug.includes('tax') || slug.includes('paycheck') || slug.includes('budget') || slug.includes('invest') || slug.includes('fire') || slug.includes('debt') || slug.includes('credit') || slug.includes('fd') || slug.includes('savings') || slug.includes('retirement') || slug.includes('inflation') || slug.includes('refinance') || slug.includes('rent') || slug.includes('emi') || slug.includes('amortization') || slug.includes('affordability')) {
      enrichment = getFinanceContent(slug);
    } else if (file.includes('health') || slug.includes('bmi') || slug.includes('calorie') || slug.includes('tdee') || slug.includes('fitness') || slug.includes('sleep') || slug.includes('steps') || slug.includes('pregnancy')) {
      enrichment = getHealthContent(slug);
    } else if (file.includes('math') || slug.includes('math') || slug.includes('percentage') || slug.includes('fraction') || slug.includes('algebra') || slug.includes('geometry') || slug.includes('statistics') || slug.includes('probability') || slug.includes('scientific') || slug.includes('grade') || slug.includes('gpa')) {
      enrichment = getMathContent(slug);
    } else {
      enrichment = getUtilityContent(slug);
    }

    // Insert enrichment before <section class="faq-section" or before </article>
    if (html.includes('<section class="faq-section"')) {
      html = html.replace('<section class="faq-section"', `${enrichment}\n<section class="faq-section"`);
    } else if (html.includes('</article>')) {
      html = html.replace('</article>', `${enrichment}\n</article>`);
    } else if (html.includes('</main>')) {
      html = html.replace('</main>', `${enrichment}\n</main>`);
    }

    fs.writeFileSync(file, html);
    const newWords = countWords(html);
    console.log(`Enriched ${slug}: ${currentWords} -> ${newWords} words`);
    enrichedCount++;
  }
}

console.log(`Total pages enriched: ${enrichedCount}`);
